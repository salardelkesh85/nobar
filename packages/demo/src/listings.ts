import { daysAgo } from "./clock";
import type { Grade, Listing, ListingPackage } from "./types";

type Pkg = [label: string, grams: number, priceToman: number] | [label: string, grams: null, priceToman: number, units: number];

interface Opts {
  variety?: string;
  grade?: Grade;
  organic?: boolean;
  origin?: string;
  nobar?: boolean;
  preorderInDays?: number;
  tags?: string[];
  stockKg?: number;
}

function L(
  id: string,
  shopId: string,
  produceTypeId: string,
  title: string,
  description: string,
  harvestDaysAgo: number,
  publishedDaysAgo: number,
  packages: Pkg[],
  shopCity: string,
  o: Opts = {},
): Listing {
  const pkgs: ListingPackage[] = packages.map((p, i) =>
    p[1] === null
      ? { id: `${id}-p${i + 1}`, label: p[0], units: p[3], priceRial: p[2] * 10 }
      : { id: `${id}-p${i + 1}`, label: p[0], netGrams: p[1], priceRial: p[2] * 10 },
  );
  const listing: Listing = {
    id,
    slug: `${title.replace(/[—–]/g, " ").trim().replace(/\s+/g, "-")}-${id}`,
    shopId,
    produceTypeId,
    title,
    description,
    grade: o.grade ?? "GRADE_1",
    originCityId: o.origin ?? shopCity,
    isOrganic: o.organic ?? false,
    harvestedAt: daysAgo(harvestDaysAgo, 7),
    stockBase: (o.stockKg ?? 400) * (packages[0]?.[1] === null ? 1 : 1000),
    packages: pkgs,
    publishedAt: daysAgo(publishedDaysAgo, 11),
    tags: o.tags ?? [],
    status: "PUBLISHED",
  };
  if (o.variety) listing.variety = o.variety;
  if (o.nobar) listing.nobarUntil = daysAgo(publishedDaysAgo - 14);
  if (o.preorderInDays !== undefined) {
    listing.isPreorder = true;
    listing.preorderDispatchFrom = daysAgo(-o.preorderInDays);
  }
  return listing;
}

